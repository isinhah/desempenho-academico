-- Controle de arquivos CSV mensais e de seus dados brutos importados
CREATE TABLE IF NOT EXISTS public.importacao_arquivo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caminho_storage TEXT NOT NULL UNIQUE,
    nome_arquivo TEXT NOT NULL,
    mes_referencia DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDENTE',
    linhas_lidas INTEGER NOT NULL DEFAULT 0,
    linhas_importadas INTEGER NOT NULL DEFAULT 0,
    linhas_rejeitadas INTEGER NOT NULL DEFAULT 0,
    mensagem_erro TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processado_em TIMESTAMPTZ,
    CONSTRAINT ck_importacao_arquivo_mes_referencia
        CHECK (EXTRACT(DAY FROM mes_referencia) = 1),
    CONSTRAINT ck_importacao_arquivo_status
        CHECK (status IN ('PENDENTE', 'PROCESSANDO', 'CONCLUIDA', 'FALHA')),
    CONSTRAINT ck_importacao_arquivo_contadores
        CHECK (
            linhas_lidas >= 0
            AND linhas_importadas >= 0
            AND linhas_rejeitadas >= 0
        )
);

CREATE TABLE IF NOT EXISTS public.curso_indicador_bruto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id BIGINT NOT NULL
        REFERENCES public.importacao_arquivo(id) ON DELETE RESTRICT,
    escola TEXT NOT NULL,
    curso TEXT NOT NULL,
    alunos_ativos INTEGER NOT NULL,
    alunos_evadidos INTEGER NOT NULL,
    mes_referencia DATE NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_curso_indicador_bruto_escola_curso_mes
        UNIQUE (escola, curso, mes_referencia),
    CONSTRAINT ck_curso_indicador_bruto_mes_referencia
        CHECK (EXTRACT(DAY FROM mes_referencia) = 1),
    CONSTRAINT ck_curso_indicador_bruto_quantidades
        CHECK (
            alunos_ativos > 0
            AND alunos_evadidos >= 0
            AND alunos_evadidos <= alunos_ativos
        )
);

CREATE INDEX IF NOT EXISTS ix_curso_indicador_bruto_mes_referencia
    ON public.curso_indicador_bruto (mes_referencia);

CREATE INDEX IF NOT EXISTS ix_curso_indicador_bruto_importacao_id
    ON public.curso_indicador_bruto (importacao_id);
